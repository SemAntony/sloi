#!/usr/bin/env node
/**
 * A2b: сборка артефактов @sloi/tokens из DTCG-источника (packages/tokens/source/).
 *
 * Style Dictionary загружает файлы, проверяет ссылки {a.b} и раскрывает типы;
 * сами артефакты формируются здесь, чтобы сохранить прежний CSS-контракт
 * (те же имена `--sloi-*`, те же селекторы, алиасы как var(--…)).
 *
 * Выход (в --out, по умолчанию packages/tokens/src):
 *   palette.css, colors.css, tokens.css, tokens.json (DTCG, light), tokens.dark.json,
 *   tokens.js, tokens.d.ts
 *
 * Запуск: node scripts/build-tokens.mjs [--out <каталог>]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import StyleDictionary from 'style-dictionary';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = path.join(root, 'source');
const EXT = 'sloi.css';
const HEADER = '/* Generated by packages/tokens/scripts/build-tokens.mjs from source/**. Do not edit. */';

const SOURCES = {
  palette: 'primitives/palette.json',
  foundation: 'foundation.json',
  light: 'semantic/light.json',
  dark: 'semantic/dark.json'
};
const sourcePath = (key) => path.join(sourceDir, SOURCES[key]);

const cssName = (tokenPath) => `--sloi-${tokenPath.join('-')}`;

function formatDimension({ value, unit }) {
  return value === 0 && unit !== 'ms' && unit !== 's' ? '0' : `${value}${unit}`;
}

export function cssValue(token) {
  const override = token.$extensions?.[EXT];
  if (override) return override;

  const original = token.original.$value;
  if (typeof original === 'string' && /^\{[^}]+\}$/.test(original)) {
    return `var(${cssName(original.slice(1, -1).split('.'))})`;
  }

  const value = token.$value;
  switch (token.$type) {
    case 'color':
    case 'number':
    case 'fontWeight':
      return String(value);
    case 'dimension':
      return formatDimension(value);
    case 'duration':
      return `${value.value}${value.unit}`;
    case 'fontFamily':
      return value.map((name) => (/\s/.test(name) ? `'${name}'` : name)).join(', ');
    case 'cubicBezier':
      return `cubic-bezier(${value.join(', ')})`;
    default:
      throw new Error(`Нет CSS-правила для ${token.path.join('.')} ($type=${token.$type})`);
  }
}

async function load(keys) {
  const dictionary = new StyleDictionary({
    usesDtcg: true,
    source: keys.map(sourcePath),
    log: { warnings: 'disabled', verbosity: 'silent', errors: { brokenReferences: 'throw' } },
    platforms: { css: { transforms: [] } }
  });
  const { allTokens } = await dictionary.getPlatformTokens('css');
  return allTokens;
}

const declarations = (tokens, indent = '  ') =>
  tokens.map((token) => `${indent}${cssName(token.path)}: ${cssValue(token)};`).join('\n');

const block = (selector, tokens) => `${selector} {\n${declarations(tokens)}\n}`;
const fromFile = (tokens, key) => tokens.filter((token) => token.filePath.endsWith(SOURCES[key]));

function readJson(key) {
  return JSON.parse(fs.readFileSync(sourcePath(key), 'utf8'));
}

function mergeDisjoint(target, ...parts) {
  for (const part of parts) {
    for (const [key, value] of Object.entries(part)) {
      if (key in target) throw new Error(`Пересечение верхнеуровневых групп: ${key}`);
      target[key] = value;
    }
  }
  return target;
}

export async function buildTokens({ outDir }) {
  const lightTokens = await load(['palette', 'foundation', 'light']);
  const darkTokens = await load(['palette', 'foundation', 'light', 'dark']);

  const palette = fromFile(lightTokens, 'palette');
  const foundation = fromFile(lightTokens, 'foundation');
  const light = fromFile(lightTokens, 'light');
  const dark = fromFile(darkTokens, 'dark');

  const tokensJson = mergeDisjoint({}, readJson('palette'), readJson('foundation'), readJson('light'));
  const darkJson = readJson('dark');
  const json = (data) => `${JSON.stringify(data, null, 2)}\n`;

  const files = {
    'palette.css': `${HEADER}\n${block(':root', palette)}\n`,
    'colors.css': `${HEADER}\n@import './palette.css';\n\n${block(':root', light)}\n\n${block("[data-theme='dark']", dark)}\n`,
    'tokens.css': `${HEADER}\n@import './colors.css';\n\n${block(':root', foundation)}\n`,
    'tokens.json': json(tokensJson),
    'tokens.dark.json': json(darkJson),
    'tokens.js':
      `${HEADER.replace('/* ', '// ').replace(' */', '')}\n` +
      `export const TOKEN_SCHEMA_URL = 'https://www.designtokens.org/TR/2025.10/format/';\n` +
      `export const TOKENS = ${JSON.stringify(tokensJson, null, 2)};\n` +
      `export const DARK_TOKENS = ${JSON.stringify(darkJson, null, 2)};\n` +
      'export default TOKENS;\n',
    'tokens.d.ts':
      `${HEADER}\n` +
      'export interface DtcgToken {\n  $type?: string;\n  $value: unknown;\n  $description?: string;\n  $extensions?: Record<string, unknown>;\n}\n' +
      'export interface DtcgGroup {\n  [key: string]: DtcgGroup | DtcgToken;\n}\n' +
      'export const TOKEN_SCHEMA_URL: string;\nexport const TOKENS: DtcgGroup;\nexport const DARK_TOKENS: DtcgGroup;\nexport default TOKENS;\n'
  };

  fs.mkdirSync(outDir, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    fs.writeFileSync(path.join(outDir, name), content);
  }
  return {
    outDir,
    counts: {
      palette: palette.length,
      foundation: foundation.length,
      light: light.length,
      dark: dark.length
    }
  };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const outIndex = process.argv.indexOf('--out');
  const outDir = path.resolve(outIndex === -1 ? path.join(root, 'src') : process.argv[outIndex + 1]);
  const { counts } = await buildTokens({ outDir });
  console.log(`[tokens] built ${outDir}`, counts);
}
